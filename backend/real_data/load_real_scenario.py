"""
load_real_scenario.py
---------------------
Loads data/real_markets.json into the running API so the existing tabs work
on REAL markets. Changes no existing code -- it only calls the same POST
endpoints the frontend uses.

  REAL       markets: location, price per crop, capacity per crop (Agmarknet)
  SYNTHETIC  farmers (no public farmer-level dataset exists) and the fleet
             (costs are assumptions in logistics_lib_v2.VEHICLE_TYPES).
Synthetic farmers are generated by the project's own generate_scenario_v2(),
shifted to --anchor, and restricted to crops at least one loaded market quotes
(otherwise those farmers could never sell -- e.g. mango out of season).

Run from backend/ with the API up:
    python real_data/load_real_scenario.py --reset
"""
import argparse
import json
import sys
from collections import Counter
from pathlib import Path

import httpx

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))   # backend/
from logistics_lib_v2 import depot_aware_fleet_composition, generate_scenario_v2, haversine  # noqa: E402

from common import REAL_MARKETS_JSON  # noqa: E402

GEN_CENTER = (25.60, 84.90)   # hard-coded centre inside generate_scenario_v2()


def select_markets(markets, anchor, max_markets):
    usable = [m for m in markets if m["price"] and m["capacity_kg"]]
    usable.sort(key=lambda m: haversine(anchor[0], anchor[1], m["lat"], m["lng"]))
    return usable[:max_markets]


def make_farmers_and_fleet(markets, anchor, n_farmers, seed, fleet_multiplier=1):
    quoted = {c for m in markets for c in m["price"]}
    farmers, _, _ = generate_scenario_v2(n_farmers=n_farmers, n_markets=1, seed=seed)
    dlat, dlng = anchor[0] - GEN_CENTER[0], anchor[1] - GEN_CENTER[1]
    kept = []
    for f in farmers:
        if f.crop in quoted:
            f.lat += dlat
            f.lng += dlng
            kept.append(f)
    comp = depot_aware_fleet_composition(kept) if kept else {}
    comp = {t: n * fleet_multiplier for t, n in comp.items()}   # fleet size is an ASSUMPTION; see --fleet-multiplier
    return kept, comp


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--api", default="http://localhost:8000")
    ap.add_argument("--json", default=str(REAL_MARKETS_JSON))
    ap.add_argument("--anchor", default="25.60,84.90", help="lat,lng of the farmer cluster centre")
    ap.add_argument("--n-farmers", type=int, default=40)
    ap.add_argument("--max-markets", type=int, default=8, help="nearest N real markets to the anchor")
    ap.add_argument("--fleet-multiplier", type=int, default=1,
                    help="multiply the project's default synthetic fleet (~1 vehicle per 40 farmers, min 1 per type). "
                         "Default 1 can leave farmers without a truck at small scale; 2 is a common fix. "
                         "Fleet size is an assumption, not sourced data - state it in your report.")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--reset", action="store_true", help="POST /reset first (clears ALL data)")
    args = ap.parse_args(argv)

    data = json.loads(Path(args.json).read_text())
    anchor = tuple(float(x) for x in args.anchor.split(","))
    chosen = select_markets(data["markets"], anchor, args.max_markets)
    if not chosen:
        sys.exit("No usable markets in the JSON. Check build_real_markets.py output.")
    farmers, comp = make_farmers_and_fleet(chosen, anchor, args.n_farmers, args.seed, args.fleet_multiplier)
    if not farmers:
        sys.exit("No synthetic farmer grows a crop that the chosen markets quote.")

    with httpx.Client(base_url=args.api, timeout=60) as c:
        if args.reset:
            c.post("/reset").raise_for_status()
        print("Real markets loaded (API id -> mandi):")
        for m in chosen:
            r = c.post("/markets", json={"lat": m["lat"], "lng": m["lng"],
                                         "price": m["price"], "capacity_kg": m["capacity_kg"]})
            r.raise_for_status()
            d = haversine(anchor[0], anchor[1], m["lat"], m["lng"])
            print(f"  {r.json()['id']:>3} -> {m['name']} ({m['district']}), {d:.0f} km from anchor, "
                  f"crops: {', '.join(sorted(m['price']))}")
        for f in farmers:
            c.post("/farmers", json={"lat": f.lat, "lng": f.lng, "crop": f.crop, "qty_kg": round(f.qty_kg, 1),
                                     "ready_hr": round(f.ready_hr, 2), "deadline_hr": round(f.deadline_hr, 2)}
                   ).raise_for_status()
        for t, n in comp.items():
            if n:
                c.post("/vehicles", json={"type_name": t, "count": n}).raise_for_status()
    fleet = {k: v for k, v in comp.items() if v}
    print(f"\n{len(farmers)} synthetic farmers {dict(Counter(f.crop for f in farmers))}, synthetic fleet {fleet}")
    print("Now POST /plan/compute (or use the Recommended plan tab).")


if __name__ == "__main__":
    main()
